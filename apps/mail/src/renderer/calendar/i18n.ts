const tables: Record<string, Record<CalendarStringKey, string>> = { de, en }

export type CalT = Translate<CalendarStringKey>

export function calendarTranslator(lang: string): CalT {
  const table = tables[lang.slice(0, 2).toLowerCase()] ?? en
  return (key, vars) => {
    let text = table[key] ?? en[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(v)
    return text
  }
}
