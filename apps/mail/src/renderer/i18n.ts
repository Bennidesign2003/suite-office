const tables: Record<string, Record<Key, string>> = { de, en }

export type MailStringKey = Key

export function translator(lang: string): (key: Key, vars?: Record<string, string>) => string {
  const table = tables[lang.slice(0, 2)] ?? en
  return (key, vars) => {
    let text = table[key] ?? en[key]
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, v)
    return text
  }
}

/** the language the AI should write in, as a name the model understands */
export function languageName(lang: string): string {
  const names: Record<string, string> = {
    de: 'German',
    en: 'English',
    fr: 'French',
    es: 'Spanish',
    it: 'Italian',
    pt: 'Portuguese',
    nl: 'Dutch',
    pl: 'Polish',
    cs: 'Czech',
    tr: 'Turkish',
    ru: 'Russian',
    ja: 'Japanese',
    ko: 'Korean',
    zh: 'Chinese',
  }
  return names[lang.slice(0, 2)] ?? 'English'
}
